<?php

declare(strict_types=1);

namespace Tests\Feature;

use Database\Seeders\TemplateSeeder;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Illuminate\Foundation\Vite;
use Tests\TestCase;

/**
 * The share buttons in the app are progressive enhancements: without the
 * Vite JavaScript entry they silently do nothing. Guard both the Blade
 * reference and the rendered tag.
 */
final class FrontendAssetsTest extends TestCase
{
    use RefreshDatabase;

    public function test_the_assets_partial_references_the_javascript_entry(): void
    {
        $partial = file_get_contents(resource_path('views/partials/assets.blade.php'));

        $this->assertIsString($partial);
        $this->assertStringContainsString('resources/css/app.css', $partial);
        $this->assertStringContainsString('resources/js/app.js', $partial);
    }

    public function test_the_rendered_page_loads_the_built_javascript_bundle(): void
    {
        $manifestPath = public_path('build/manifest.json');

        if (! file_exists($manifestPath)) {
            $this->markTestSkipped('Run npm run build to verify the rendered asset tags.');
        }

        if (app(Vite::class)->isRunningHot()) {
            // With `npm run dev` alive the layout points at the dev server on
            // purpose, so the manifest tags only appear once hot reload stops.
            $this->markTestSkipped('Vite dev server is running; stop it to check the built bundle.');
        }

        $manifest = json_decode((string) file_get_contents($manifestPath), true);
        $script = $manifest['resources/js/app.js']['file'] ?? null;

        $this->assertIsString($script);

        $this->get('/')
            ->assertOk()
            ->assertSee($script, false);
    }

    /**
     * The icons are generated by tools/brand/build-icons.php; an empty or missing
     * file would 404 silently because the markup still looks complete.
     */
    public function test_the_brand_icon_set_is_shipped(): void
    {
        $icons = [
            'favicon.ico' => 1024,
            'favicon-32.png' => 200,
            'apple-touch-icon.png' => 500,
            'icon-192.png' => 2000,
            'icon-512.png' => 10000,
            'og-wedly.png' => 5000,
            'brand/wedly-mark-96.png' => 2000,
            'site.webmanifest' => 200,
        ];

        foreach ($icons as $file => $minimumBytes) {
            $path = public_path($file);

            $this->assertFileExists($path);
            $this->assertGreaterThanOrEqual(
                $minimumBytes,
                (int) filesize($path),
                $file.' looks truncated.',
            );
        }

        $manifest = json_decode((string) file_get_contents(public_path('site.webmanifest')), true);

        $this->assertSame('Wedly', $manifest['short_name']);

        foreach ($manifest['icons'] as $icon) {
            $this->assertFileExists(public_path(ltrim($icon['src'], '/')));
        }
    }

    public function test_the_landing_page_declares_the_brand_identity(): void
    {
        $this->get('/')
            ->assertOk()
            ->assertSee('rel="icon"', false)
            ->assertSee('rel="manifest"', false)
            ->assertSee('theme-color', false)
            ->assertSee('og-wedly.png', false)
            ->assertSee('site.webmanifest', false)
            ->assertSee('Invitation · Celebration · Forever', false)
            ->assertSee('Numos Studio', false);
    }

    public function test_the_invitation_page_carries_the_same_icons(): void
    {
        // A guest who saves an invitation to the home screen should keep the
        // brand icon, so the demo page must ship the same head partial.
        $this->seed(TemplateSeeder::class);

        $this->get(route('templates.demo', ['template' => 'classic-ivory']))
            ->assertOk()
            ->assertSee('favicon.ico', false)
            ->assertSee('apple-touch-icon.png', false);
    }
}
